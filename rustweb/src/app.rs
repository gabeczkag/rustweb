use axum::Router;
use utoipa::openapi::{path::Operation, schema::Schema, RefOr};

use crate::route::Route;

pub(crate) struct RouteMeta {
    pub method: axum::http::Method,
    pub path: &'static str,
    pub operation: Operation,
    pub schemas: Vec<(String, RefOr<Schema>)>,
}

/// Application builder.
///
/// Routes are registered explicitly:
///
/// ```ignore
/// let app = RustWeb::new("Demo", "0.1.0")
///     .route(get_user)
///     .route(create_user);
/// ```
pub struct RustWeb {
    title: String,
    version: String,
    router: Router,
    routes: Vec<RouteMeta>,
}

impl RustWeb {
    /// Create a new application with OpenAPI metadata.
    pub fn new(title: impl Into<String>, version: impl Into<String>) -> Self {
        Self {
            title: title.into(),
            version: version.into(),
            router: Router::new(),
            routes: Vec::new(),
        }
    }

    /// Register a route generated by a rustweb attribute macro.
    pub fn route<R: Route>(mut self, route: R) -> Self {
        self.routes.push(RouteMeta {
            method: route.method(),
            path: route.path(),
            operation: route.operation(),
            schemas: route.schemas(),
        });
        self.router = route.register(self.router);
        self
    }

    /// Finish the application and return the underlying axum router.
    pub fn into_router(self) -> Router {
        let _ = (&self.title, &self.version, &self.routes);
        self.router
    }
}
