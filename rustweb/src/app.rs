use axum::body::Bytes;
use axum::http::{header, HeaderMap, HeaderValue};
use axum::response::IntoResponse;
use axum::Router;
use utoipa::openapi::{path::Operation, schema::Schema, RefOr};
use utoipa_swagger_ui::SwaggerUi;

use crate::error::ApiError;
use crate::route::Route;
use crate::spec;

pub(crate) struct RouteMeta {
    pub method: axum::http::Method,
    pub path: &'static str,
    pub operation: Operation,
    pub schemas: Vec<(String, RefOr<Schema>)>,
}

/// Application builder.
///
/// Routes are registered explicitly:
///
/// ```ignore
/// let app = RustWeb::new("Demo", "0.1.0")
///     .route(get_user)
///     .route(create_user);
/// ```
pub struct RustWeb {
    pub(crate) title: String,
    pub(crate) version: String,
    pub(crate) router: Router,
    pub(crate) routes: Vec<RouteMeta>,
    pub(crate) docs_path: Option<String>,
    pub(crate) openapi_path: String,
    pub(crate) spa: Option<Bytes>,
    pub(crate) spa_headers: HeaderMap,
}

impl RustWeb {
    /// Create a new application with OpenAPI metadata.
    pub fn new(title: impl Into<String>, version: impl Into<String>) -> Self {
        Self {
            title: title.into(),
            version: version.into(),
            router: Router::new(),
            routes: Vec::new(),
            docs_path: Some("/docs".to_owned()),
            openapi_path: "/openapi.json".to_owned(),
            spa: None,
            spa_headers: HeaderMap::new(),
        }
    }

    /// Register a route generated by a rustweb attribute macro.
    pub fn route<R: Route>(mut self, route: R) -> Self {
        self.routes.push(RouteMeta {
            method: route.method(),
            path: route.path(),
            operation: route.operation(),
            schemas: route.schemas(),
        });
        self.router = route.register(self.router);
        self
    }

    /// Change the Swagger UI path (default: `/docs`).
    pub fn docs(mut self, path: impl Into<String>) -> Self {
        self.docs_path = Some(path.into());
        self
    }

    /// Change the OpenAPI JSON path (default: `/openapi.json`).
    pub fn openapi_path(mut self, path: impl Into<String>) -> Self {
        self.openapi_path = path.into();
        self
    }

    /// Disable both Swagger UI and the OpenAPI endpoint.
    pub fn no_docs(mut self) -> Self {
        self.docs_path = None;
        self
    }

    /// Finish the application and return the underlying axum router.
    pub fn into_router(self) -> Router {
        let spec = spec::build(&self.title, &self.version, &self.routes);

        let mut router = self.router;
        if let Some(docs_path) = self.docs_path {
            router = router.merge(SwaggerUi::new(docs_path).url(self.openapi_path, spec));
        }

        match self.spa {
            Some(html) => {
                let mut headers = self.spa_headers;
                if !headers.contains_key(header::CONTENT_TYPE) {
                    headers.insert(
                        header::CONTENT_TYPE,
                        HeaderValue::from_static("text/html; charset=utf-8"),
                    );
                }

                router.fallback(move || {
                    let html = html.clone();
                    let headers = headers.clone();
                    async move {
                        let mut response = html.into_response();
                        *response.headers_mut() = headers;
                        response
                    }
                })
            }
            None => router.fallback(|| async { ApiError::not_found("Not Found") }),
        }
    }

    /// Bind a TCP listener and serve the application.
    pub async fn serve(self, address: impl tokio::net::ToSocketAddrs) -> std::io::Result<()> {
        let listener = tokio::net::TcpListener::bind(address).await?;
        axum::serve(listener, self.into_router()).await
    }
}
